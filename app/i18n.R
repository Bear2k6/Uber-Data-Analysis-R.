tr <- function(key, lang = "vi", ...) {
  if (!lang %in% names(translations)) stop("Unsupported language: ", lang)
  result <- unname(translations[[lang]][key])
  if (anyNA(result)) stop("Missing translation: ", paste(key[is.na(result)], collapse = ", "))
  if (length(list(...))) result <- sprintf(result, ...)
  enc2utf8(result)
}
# Weekday means a dimension name OR a day-type value: use context explicitly.
display_values <- function(x, lang = "vi", dimension = NULL) {
  values <- as.character(x)
  keys <- if (identical(dimension, "DayType")) ifelse(values == "Weekday", "day_weekday", values) else values
  known <- keys %in% names(translations[[lang]])
  values[known] <- tr(keys[known], lang)
  values
}
localized_choices <- function(values, lang = "vi", dimension = NULL, all = TRUE) {
  if (all) values <- c("All", values)
  setNames(as.character(values), display_values(values, lang, dimension))
}
fmt_number <- function(x, lang = "vi", digits = 0) {
  trimws(formatC(x, format = "f", digits = digits,
    big.mark = if (lang == "vi") "." else ",", decimal.mark = if (lang == "vi") "," else "."))
}
fmt_percent <- function(x, lang = "vi", digits = 2) paste0(fmt_number(x, lang, digits), "%")
fmt_date <- function(x, lang = "vi") {
  x <- as.Date(x)
  if (lang == "vi") return(format(x, "%d/%m/%Y"))
  paste0(month.abb[as.integer(format(x,"%m"))], " ", as.integer(format(x,"%d")), ", ", format(x,"%Y"))
}
fmt_dimension <- function(x, dimension, lang = "vi") {
  if (dimension == "Date") return(fmt_date(x, lang))
  if (dimension == "Time") return(paste(fmt_date(as.Date(x,tz="UTC"),lang),format(x,"%H:%M",tz="UTC")))
  if (dimension == "Hour") return(sprintf("%02d:00",as.integer(x)))
  display_values(x,lang,dimension)
}
